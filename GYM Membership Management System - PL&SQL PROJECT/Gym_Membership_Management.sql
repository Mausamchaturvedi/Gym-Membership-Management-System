-- ============================================================
-- SECTION 3: STORED PROCEDURE - REGISTER A MEMBER
-- ============================================================

CREATE OR REPLACE PROCEDURE register_gym_member (
    p_full_name IN VARCHAR2,
    p_gender    IN VARCHAR2,
    p_phone     IN VARCHAR2
)
AS
BEGIN
    INSERT INTO gym_members (full_name, gender, phone)
    VALUES (p_full_name, p_gender, p_phone);

    DBMS_OUTPUT.PUT_LINE('Member registered successfully: ' || p_full_name);
END;
/

-- ============================================================
-- SECTION 4: STORED PROCEDURE - RECORD PAYMENT
-- ============================================================

CREATE OR REPLACE PROCEDURE record_gym_payment (
    p_member_id IN NUMBER,
    p_amount    IN NUMBER,
    p_method    IN VARCHAR2
)
AS
    v_member_count NUMBER;
    v_method       VARCHAR2(30);
BEGIN
    IF p_amount IS NULL OR p_amount <= 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Payment amount must be greater than zero.');
    END IF;

    v_method := UPPER(TRIM(p_method));

    IF v_method IS NULL OR v_method NOT IN ('CASH', 'UPI', 'CARD', 'BANK TRANSFER') THEN
        RAISE_APPLICATION_ERROR(-20002, 'Invalid payment method.');
    END IF;

    SELECT COUNT(*)
    INTO v_member_count
    FROM gym_members
    WHERE member_id = p_member_id;

    IF v_member_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20003, 'Member does not exist.');
    END IF;

    INSERT INTO gym_payments
        (member_id, amount, payment_method, payment_status)
    VALUES
        (p_member_id, p_amount, v_method, 'PAID');

    DBMS_OUTPUT.PUT_LINE('Payment recorded successfully.');
END;
/

-- ============================================================
-- SECTION 5: FUNCTION - TOTAL SUCCESSFUL PAYMENTS PER MEMBER
-- ============================================================

CREATE OR REPLACE FUNCTION get_total_payments (
    p_member_id IN NUMBER
)
RETURN NUMBER
AS
    v_total NUMBER(10,2);
BEGIN
    SELECT NVL(SUM(amount), 0)
    INTO v_total
    FROM gym_payments
    WHERE member_id = p_member_id
      AND payment_status = 'PAID';

    RETURN v_total;
END;
/

-- ============================================================
-- SECTION 6: TRIGGER - VALIDATE PAYMENT AND NORMALIZE VALUES
-- ============================================================

CREATE OR REPLACE TRIGGER trg_validate_gym_payment
BEFORE INSERT OR UPDATE ON gym_payments
FOR EACH ROW
BEGIN
    IF :NEW.amount IS NULL OR :NEW.amount <= 0 THEN
        RAISE_APPLICATION_ERROR(-20010, 'Payment amount must be greater than zero.');
    END IF;

    IF :NEW.payment_method IS NOT NULL THEN
        :NEW.payment_method := UPPER(TRIM(:NEW.payment_method));
    END IF;

    IF :NEW.payment_status IS NOT NULL THEN
        :NEW.payment_status := UPPER(TRIM(:NEW.payment_status));
    END IF;
END;
/

-- ============================================================
-- SECTION 7: STORED PROCEDURE - RENEW MEMBERSHIP
-- ============================================================

CREATE OR REPLACE PROCEDURE renew_gym_membership (
    p_membership_id IN NUMBER,
    p_plan_id       IN NUMBER
)
AS
    v_duration NUMBER;
    v_end_date DATE;
BEGIN
    SELECT duration_months
    INTO v_duration
    FROM membership_plans
    WHERE plan_id = p_plan_id;

    SELECT end_date
    INTO v_end_date
    FROM gym_memberships
    WHERE membership_id = p_membership_id
    FOR UPDATE;

    UPDATE gym_memberships
    SET end_date = ADD_MONTHS(GREATEST(v_end_date, TRUNC(SYSDATE)), v_duration),
        plan_id = p_plan_id,
        membership_status = 'ACTIVE'
    WHERE membership_id = p_membership_id;

    DBMS_OUTPUT.PUT_LINE('Membership renewed successfully.');

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20021, 'Membership record or plan does not exist.');
END;
/

