-- SECTION 10: REPORT QUERIES
-- Run each SELECT query separately if your worksheet requires it.
-- ============================================================

-- 10A. Members
SELECT * FROM gym_members ORDER BY member_id;

-- 10B. Membership plans
SELECT * FROM membership_plans ORDER BY plan_id;

-- 10C. Trainers
SELECT * FROM gym_trainers ORDER BY trainer_id;

-- 10D. Payments with member names
SELECT p.payment_id, m.full_name, p.amount, p.payment_date,
       p.payment_method, p.payment_status
FROM gym_payments p
JOIN gym_members m ON m.member_id = p.member_id
ORDER BY p.payment_id;

-- 10E. Attendance report
SELECT a.attendance_id, m.full_name, a.attendance_date, a.attendance_status
FROM gym_attendance a
JOIN gym_members m ON m.member_id = a.member_id
ORDER BY a.attendance_date DESC;

-- 10F. Active/expired membership report
SELECT m.member_id, m.full_name, p.plan_name, gm.start_date, gm.end_date,
       CASE
           WHEN gm.membership_status = 'CANCELLED' THEN 'CANCELLED'
           WHEN gm.end_date < TRUNC(SYSDATE) THEN 'EXPIRED'
           ELSE 'ACTIVE'
       END AS current_status
FROM gym_memberships gm
JOIN gym_members m ON m.member_id = gm.member_id
JOIN membership_plans p ON p.plan_id = gm.plan_id
ORDER BY gm.end_date;

-- 10G. Monthly revenue
SELECT TO_CHAR(payment_date, 'YYYY-MM') AS payment_month,
       SUM(amount) AS total_revenue,
       COUNT(*) AS total_payments
FROM gym_payments
WHERE payment_status = 'PAID'
GROUP BY TO_CHAR(payment_date, 'YYYY-MM')
ORDER BY payment_month;

-- 10H. Attendance totals
SELECT m.member_id, m.full_name, COUNT(a.attendance_id) AS total_visits
FROM gym_members m
LEFT JOIN gym_attendance a
    ON a.member_id = m.member_id
   AND a.attendance_status = 'PRESENT'
GROUP BY m.member_id, m.full_name
ORDER BY total_visits DESC;

-- 10I. Total paid per member
SELECT m.member_id, m.full_name,
       get_total_payments(m.member_id) AS total_paid
FROM gym_members m
ORDER BY m.member_id;

-- 10J. Object verification
SELECT object_name, object_type, status
FROM user_objects
WHERE object_name IN (
    'GYM_MEMBERS', 'MEMBERSHIP_PLANS', 'GYM_MEMBERSHIPS',
    'GYM_TRAINERS', 'GYM_PAYMENTS', 'GYM_ATTENDANCE',
    'REGISTER_GYM_MEMBER', 'RECORD_GYM_PAYMENT',
    'GET_TOTAL_PAYMENTS', 'TRG_VALIDATE_GYM_PAYMENT',
    'RENEW_GYM_MEMBERSHIP'
)
ORDER BY object_type, object_name;

