CREATE TABLE gym_members (
    member_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(100) NOT NULL,
    gender VARCHAR2(10),
    phone VARCHAR2(15),
    join_date DATE DEFAULT SYSDATE,
    membership_status VARCHAR2(20) DEFAULT 'ACTIVE'
);

CREATE TABLE membership_plans (
    plan_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_name VARCHAR2(50) NOT NULL,
    duration_months NUMBER NOT NULL,
    fee NUMBER(10,2) NOT NULL,
    CONSTRAINT chk_plan_duration CHECK (duration_months > 0),
    CONSTRAINT chk_plan_fee CHECK (fee >= 0)
);

CREATE TABLE gym_memberships (
    membership_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id NUMBER NOT NULL,
    plan_id NUMBER NOT NULL,
    start_date DATE DEFAULT SYSDATE NOT NULL,
    end_date DATE NOT NULL,
    membership_status VARCHAR2(20) DEFAULT 'ACTIVE',
    CONSTRAINT fk_gm_member
        FOREIGN KEY (member_id) REFERENCES gym_members(member_id),
    CONSTRAINT fk_gm_plan
        FOREIGN KEY (plan_id) REFERENCES membership_plans(plan_id),
    CONSTRAINT chk_gm_dates CHECK (end_date >= start_date)
);

CREATE TABLE gym_trainers (
    trainer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainer_name VARCHAR2(100) NOT NULL,
    specialization VARCHAR2(100),
    phone VARCHAR2(15),
    salary NUMBER(10,2),
    CONSTRAINT chk_trainer_salary CHECK (salary >= 0)
);

CREATE TABLE gym_payments (
    payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id NUMBER NOT NULL,
    amount NUMBER(10,2) NOT NULL,
    payment_date DATE DEFAULT SYSDATE,
    payment_method VARCHAR2(30),
    payment_status VARCHAR2(20) DEFAULT 'PAID',
    CONSTRAINT fk_payment_member
        FOREIGN KEY (member_id) REFERENCES gym_members(member_id),
    CONSTRAINT chk_payment_amount CHECK (amount > 0),
    CONSTRAINT chk_payment_method
        CHECK (payment_method IN ('CASH', 'UPI', 'CARD', 'BANK TRANSFER')),
    CONSTRAINT chk_payment_status
        CHECK (payment_status IN ('PAID', 'PENDING', 'FAILED'))
);

CREATE TABLE gym_attendance (
    attendance_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id NUMBER NOT NULL,
    attendance_date DATE DEFAULT SYSDATE,
    attendance_status VARCHAR2(20) DEFAULT 'PRESENT',
    CONSTRAINT fk_attendance_member
        FOREIGN KEY (member_id) REFERENCES gym_members(member_id),
    CONSTRAINT chk_attendance_status
        CHECK (attendance_status IN ('PRESENT', 'ABSENT')),
    CONSTRAINT uq_member_attendance UNIQUE (member_id, attendance_date)
);

